#!/usr/bin/env bash
# Native PostgreSQL 16 for Rakazo, using Postgres.app v2.9.7 binaries copied
# under ./postgres. No launchd, no system paths, no Homebrew.
#
# Usage: ./pg-setup.sh [setup|start|stop|status]
#   setup (default)  initdb when missing, start when stopped, create role/db, verify
#   start            start an existing cluster (initializes it if missing)
#   stop             stop the cluster (data is kept)
#   status           show pg_ctl status and connection check
set -euo pipefail

BASE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PGBIN="$BASE/postgres/bin"
PGDATA="$BASE/pgdata"
PORT=55432
SOCKDIR="$BASE/run"
LOGDIR="$BASE/logs"
ENVFILE="$BASE/env.postgres"

die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo "==> $*"; }

[ -x "$PGBIN/initdb" ] || die "PostgreSQL binaries missing at $PGBIN (expected postgres/bin/initdb)"

running() { "$PGBIN/pg_ctl" -D "$PGDATA" status >/dev/null 2>&1; }

stop_cluster() {
  if running; then
    log "Stopping PostgreSQL at $PGDATA"
    "$PGBIN/pg_ctl" -D "$PGDATA" -m fast -w stop
  else
    echo "PostgreSQL is not running."
  fi
}

show_status() {
  "$PGBIN/pg_ctl" -D "$PGDATA" status || true
  if running; then
    "$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U rakazo -d rakazo -tAc \
      "SELECT current_user || '@' || current_database() || ' / ' || version();"
  fi
}

init_cluster() {
  log "Initializing cluster at $PGDATA (UTF8, locale C)"
  "$PGBIN/initdb" -D "$PGDATA" -U rakazo -E UTF8 --locale=C -A trust >/dev/null
  # Fixed settings live in the cluster so plain pg_ctl/pg_isready agree after reboots.
  cat >>"$PGDATA/postgresql.conf" <<CONF

# --- rakazo-native ---
port = $PORT
listen_addresses = '127.0.0.1'
unix_socket_directories = '$SOCKDIR'
CONF
  # trust only on loopback; the unix socket lives in a user-private directory.
  cat >"$PGDATA/pg_hba.conf" <<'HBA'
# Rakazo native cluster: trust is limited to loopback.
# TYPE  DATABASE  USER  ADDRESS       METHOD
local   all       all                 trust
host    all       all   127.0.0.1/32  trust
HBA
}

start_cluster() {
  if running; then
    log "PostgreSQL already running (port $PORT)"
    return
  fi
  log "Starting PostgreSQL on 127.0.0.1:$PORT"
  if ! "$PGBIN/pg_ctl" -D "$PGDATA" -l "$LOGDIR/postgres.log" -w -t 60 start; then
    echo "---- last lines of $LOGDIR/postgres.log ----" >&2
    tail -n 20 "$LOGDIR/postgres.log" >&2 || true
    die "pg_ctl start failed"
  fi
  "$PGBIN/pg_isready" -h 127.0.0.1 -p "$PORT" -U rakazo -q ||
    die "server is not accepting connections on 127.0.0.1:$PORT"
}

load_or_create_env() {
  if [ -f "$ENVFILE" ]; then
    # shellcheck disable=SC1090
    . "$ENVFILE"
    [ -n "${POSTGRES_PASSWORD:-}" ] || die "$ENVFILE exists but POSTGRES_PASSWORD is empty"
    [ -n "${POSTGRES_APP_PASSWORD:-}" ] || die "$ENVFILE exists but POSTGRES_APP_PASSWORD is empty"
  else
    POSTGRES_PASSWORD="$(openssl rand -hex 24)"
    POSTGRES_APP_PASSWORD="$(openssl rand -hex 24)"
    umask 077
    cat >"$ENVFILE" <<ENV
# Generated by pg-setup.sh on $(date '+%F %T')
# Source it:  set -a; . $ENVFILE; set +a
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_APP_PASSWORD=$POSTGRES_APP_PASSWORD
DATABASE_MIGRATION_URL=postgresql://rakazo:$POSTGRES_PASSWORD@127.0.0.1:$PORT/rakazo
DATABASE_URL=postgresql://rakazo_app:$POSTGRES_APP_PASSWORD@127.0.0.1:$PORT/rakazo
ENV
    chmod 600 "$ENVFILE"
    log "Wrote credentials to $ENVFILE"
  fi
}

ensure_role_and_db() {
  local owner_psql=("$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U rakazo -d postgres -v ON_ERROR_STOP=1 -tAq)
  if [ "$("${owner_psql[@]}" -c "SELECT 1 FROM pg_roles WHERE rolname = 'rakazo'")" != "1" ]; then
    log "Creating role rakazo"
    "${owner_psql[@]}" -c "CREATE ROLE rakazo LOGIN SUPERUSER" >/dev/null
  fi
  "${owner_psql[@]}" -c "ALTER ROLE rakazo PASSWORD '$POSTGRES_PASSWORD'" >/dev/null
  if [ "$("${owner_psql[@]}" -c "SELECT 1 FROM pg_database WHERE datname = 'rakazo'")" != "1" ]; then
    log "Creating database rakazo owned by rakazo"
    "${owner_psql[@]}" -c "CREATE DATABASE rakazo OWNER rakazo" >/dev/null
  fi
}

verify() {
  local row
  row="$("$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U rakazo -d rakazo -v ON_ERROR_STOP=1 -tAq \
    -c "SELECT current_user || '@' || current_database() || ' | ' || version()")"
  case "$row" in
    rakazo@rakazo*) log "Verified: $row" ;;
    *) die "connection check returned unexpected row: $row" ;;
  esac
}

setup() {
  [ -f "$PGDATA/PG_VERSION" ] || init_cluster
  start_cluster
  load_or_create_env
  ensure_role_and_db
  verify
  echo
  echo "PostgreSQL 16 ready on 127.0.0.1:$PORT (data: $PGDATA)"
  echo "  Start: $BASE/pg-setup.sh start"
  echo "  Stop:  $BASE/pg-setup.sh stop"
  echo "  Env:   $ENVFILE"
}

mkdir -p "$SOCKDIR" "$LOGDIR"
chmod 700 "$SOCKDIR"

case "${1:-setup}" in
  setup|start) setup ;;
  stop) stop_cluster ;;
  status) show_status ;;
  *) die "unknown command '$1' (use: setup|start|stop|status)" ;;
esac
